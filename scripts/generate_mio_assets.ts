import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const spriteDirectory = join(projectRoot, "internal/web/mio");
const generatedFile = join(projectRoot, "internal/web/src/mio-assets.generated.ts");
const spriteNames = ["angry", "concerned", "curious", "happy", "idle", "looking", "sleeping", "worried"];

async function main(): Promise<void> {
    const entries: string[] = [];
    for (const name of spriteNames) {
        const filename = `mio_pose_${name}.png`;
        const path = join(spriteDirectory, filename);
        const bytes = await readFile(path);
        const hash = createHash("sha256").update(bytes).digest("hex");
        entries.push(`    ${name}: "/static/mio/${basename(path)}?v=${hash}",`);
    }

    const source = `// Generated by scripts/generate_mio_assets.ts. Do not edit by hand.\nexport const MIO_SPRITES = {\n${entries.join("\n")}\n} as const;\n`;
    await writeFile(generatedFile, source, "utf8");
}

await main();
